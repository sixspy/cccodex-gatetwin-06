"""出站孤儿旁路（主链路模块）。

全局架构口径（唯一贯彻，禁止分叉）：**当场旁路终态**。

无在途开腿的出站事件，在装载当场即按异常链路终态处置：
- 进旁路匣（原因=出站孤儿），刷卡点命运同成败置为「已旁路」；
- 不写行程账、不造虚进、不开任何形式的待配缓冲（缓冲键恒为空）；
- 旁路为终态：后续同卡再进站只正常开新腿，不回放、不配对此笔。

另一套「出站待配缓冲」口径全局不采用：本模块不建缓冲表、不写缓冲行，
只读视图以 ``缓冲键=None`` 显式区别于缓冲口径，保证两口径在
「单独灌一笔出站」瞬间是否有旁路行/缓冲行可区分。
"""

import json

from app.seed import 此刻

NAME = "出站孤儿旁路"
口径 = "当场旁路终态"
旁路原因 = "出站孤儿"


def 落孤儿旁路(conn, 事件: dict, 处理时: str) -> int:
    """无开腿出站的唯一落盘入口：刷卡命运与旁路匣同事务同成败。

    返回旁路匣编号。调用方必须在外层事务内调用；本函数不自行 commit，
    任一写入失败由外层整批回滚，杜绝「刷卡已入流而旁路缺失」的半截态。
    """
    事件编号 = 事件["事件编号"]
    卡号 = 事件["卡号"]
    cur = conn.execute(
        "INSERT INTO 旁路匣(原因, 卡号, 事件编号, 载荷, 时刻) VALUES (?,?,?,?,?)",
        (旁路原因, 卡号, 事件编号, json.dumps(事件, ensure_ascii=False), 处理时),
    )
    旁路键 = cur.lastrowid
    conn.execute(
        "UPDATE 刷卡点 SET 命运=?, 行程键=? WHERE 事件编号=?",
        ("已旁路", "", 事件编号),
    )
    return 旁路键


def 只读视图(conn, 卡号: str = "", 事件编号: str = "") -> list[dict]:
    """孤儿出站只读接口数据源。

    口径 A 下视图只认旁路匣原因='出站孤儿'；每行给出卡号、出站事件、
    旁路键与恒空的缓冲键，以及 valid 裁决。valid 为真当且仅当：
    对应刷卡点存在、方向出站、命运已旁路、无行程键，且行程账确无此行。
    """
    sql = "SELECT * FROM 旁路匣 WHERE 原因=?"
    参数 = [旁路原因]
    if 卡号:
        sql += " AND 卡号=?"
        参数.append(卡号)
    if 事件编号:
        sql += " AND 事件编号=?"
        参数.append(事件编号)
    sql += " ORDER BY 编号 DESC"

    out = []
    for 匣 in conn.execute(sql, 参数).fetchall():
        刷 = conn.execute(
            "SELECT * FROM 刷卡点 WHERE 事件编号=?", (匣["事件编号"],)
        ).fetchone()
        行程 = conn.execute(
            "SELECT 1 FROM 行程账 WHERE 出站事件编号=? LIMIT 1", (匣["事件编号"],)
        ).fetchone()
        问题 = []
        if 刷 is None:
            问题.append("缺刷卡点")
        else:
            if 刷["方向"] != "出站":
                问题.append("方向非出站")
            if 刷["命运"] != "已旁路":
                问题.append(f"命运={刷['命运']}非已旁路")
            if 刷["行程键"]:
                问题.append("携带行程键")
            if 刷["卡号"] != 匣["卡号"]:
                问题.append("卡号不一致")
        if 行程 is not None:
            问题.append("行程账双落")
        out.append(
            {
                "卡号": 匣["卡号"],
                "出站事件编号": 匣["事件编号"],
                "处置": "旁路",
                "旁路键": 匣["编号"],
                "缓冲键": None,
                "valid": not 问题,
                "口径": 口径,
                "时刻": 匣["时刻"],
                "问题": 问题,
            }
        )
    return out
